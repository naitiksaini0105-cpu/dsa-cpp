#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 5;

    cout << "Addition :" << a + b << endl;
    cout << "Subtraction :" << a - b << endl;
    cout << "MUltiplication :" << a * b << endl;
    cout << "Division : " << a / b << endl;
    cout << "reminder:" << a % b << endl;

    cout << "a>b :" << (a > b) << endl;
    cout << "a==b: " << (a == b) << endl;

    return 0;
}